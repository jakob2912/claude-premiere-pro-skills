#!/usr/bin/env python3
"""Generates the HyperFrames composition for transitions + end card (V2) from edit.js.
Usage:  .venv/bin/python <skill-dir>/scripts/gen_transitions.py graphics/<film>/A
Reads <dir>/edit.js (from build_imagefilm.py js) and <dir>/endcard.html (end card markup +
<script>function endcard(tl, t0){…}</script>). Writes <dir>/comp-transitions/index.html.
Outside the transitions the composition is transparent; it is rendered as ProRes 4444 with alpha.
"""
import sys, json, pathlib, os

ROOT = pathlib.Path.cwd()  # run from the project folder
D = ROOT / sys.argv[1]
js = (D / "edit.js").read_text()
EDIT = json.loads(js[js.index("=") + 1: js.rindex(";")])
C = D / "comp-transitions"
C.mkdir(exist_ok=True)
for name, target in (("assets", "../../assets"), ("shots", "../shots"), ("edit.js", "../edit.js")):
    if not (C / name).is_symlink():
        os.symlink(target, C / name)
card = (D / "endcard.html").read_text() if (D / "endcard.html").exists() else ""

els, svgs, calls = [], [], []
for i, t in enumerate(EDIT["transitions"]):
    d, c = t["dur"], t["cut"]
    t0 = round(c - d, 4) if t["type"] == "tocard" else round(c - d / 2, 4)  # end card: the fade ends exactly at the cut
    if t["type"] == "flashcard":
        t0, d = round(c - 0.18, 4), 0.18  # the flash builds up just before the cut, then the end card holds
    for side, track in (("a", 2 * i), ("b", 2 * i + 1)):
        m = t[side]
        if not m:
            continue
        style = "" if side == "a" else "opacity:0;"
        els.append(f'<div class="tw" id="t{i}{side}" style="{style}filter:url(#tb{i})"><video id="t{i}v{side}" class="clip" '
                   f'src="{m["file"]}" data-start="{t0}" data-duration="{d}" data-media-start="{round(m["media"] - (c - t0), 4)}" '
                   f'data-track-index="{track}" muted playsinline></video></div>')
    if t["type"] in ("bloom", "flash", "flashcard"):
        els.append(f'<div class="fx {"flash" if t["type"] == "flashcard" else t["type"]}" id="t{i}fx"></div>')
    svgs.append(f'<filter id="tb{i}" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur id="tb{i}g" stdDeviation="0 0"/></filter>')
    b = f'"#t{i}b"' if t["b"] else "null"
    calls.append(f'Transitions["{t["type"]}"](tl, {{ a: "#t{i}a", b: {b}, fx: "#t{i}fx", blur: "#tb{i}g" }}, {t0}, {c}, {d});')

# scenes on V2: split screen (a V1 shot on top, an extra shot below), slides together on the beat
SH = {x["id"]: x for x in EDIT["shots"]}
for i, sc in enumerate(EDIT.get("scenes", [])):
    if sc["type"] != "split":
        continue
    top, bot = SH[sc["top"]], EDIT["extras"][sc["bottom"]]
    t, d = top["start"], round(top["end"] - top["start"], 4)
    halves = []
    for side, m, track in (("t", top, 100 + 2 * i), ("b", bot, 101 + 2 * i)):
        halves.append(f'<div class="half {side}" id="sc{i}{side}"><video id="sc{i}v{side}" class="clip" src="{m["file"]}" data-start="{t}" '
                      f'data-duration="{d}" data-media-start="{m["head"]}" data-track-index="{track}" muted playsinline></video></div>')
    els.append(f'<div class="split" id="sc{i}">{"".join(halves)}<div class="divider" id="sc{i}d"></div></div>')
    calls.append(f'tl.set("#sc{i}", {{ opacity: 1 }}, {t}); '
                 f'tl.fromTo("#sc{i}t", {{ xPercent: -100 }}, {{ xPercent: 0, duration: 0.25, ease: "expo.out" }}, {t}); '
                 f'tl.fromTo("#sc{i}b", {{ xPercent: 100 }}, {{ xPercent: 0, duration: 0.25, ease: "expo.out" }}, {t}); '
                 f'tl.fromTo("#sc{i}d", {{ scaleX: 0 }}, {{ scaleX: 1, duration: 0.4, ease: "expo.inOut" }}, {t + 0.08}); '
                 f'tl.fromTo(["#sc{i}t video", "#sc{i}b video"], {{ scale: 1.06 }}, {{ scale: 1, duration: 0.35, ease: "expo.out" }}, {t} + 2 * EDIT.beat); '
                 f'tl.fromTo("#sc{i}d", {{ scaleY: 2.2 }}, {{ scaleY: 1, duration: 0.3, ease: "expo.out" }}, {t} + 2 * EDIT.beat); '
                 f'tl.set("#sc{i}", {{ opacity: 0 }}, {round(t + d, 4)});')

total = EDIT["total"]
nl = "\n      "
html = f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1920" />
    <title>{EDIT['name']} – transitions + end card</title>
    <link rel="stylesheet" href="assets/brand.css" />
    <script src="assets/gsap.min.js"></script>
    <script src="assets/transitions.js"></script>
    <script src="edit.js"></script>
  </head>
  <body>
    <!-- generated by gen_transitions.py, do not edit by hand -->
    <div id="root" data-composition-id="transitions" data-start="0" data-width="1080" data-height="1920" data-duration="{total}" data-fps="30">
      <svg width="0" height="0" style="position:absolute">{''.join(svgs)}</svg>
      {nl.join(els)}
      {card}
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
      {nl.join(calls)}
      if (typeof endcard === "function") endcard(tl, {EDIT['shots_end']});
      tl.set({{}}, {{}}, {total});
      window.__timelines = window.__timelines || {{}};
      window.__timelines["transitions"] = tl;
    </script>
  </body>
</html>
"""
(C / "index.html").write_text(html)
print(f"{(C / 'index.html').relative_to(ROOT)}: {len(EDIT['transitions'])} transitions, {total:.2f}s")
